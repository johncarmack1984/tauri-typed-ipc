#!/bin/sh
# Compile-time scaling: how tauri-typed-ipc's macro cost grows with the number of
# procedures in one trait. Generates a fixture crate, warms the dependency
# tree once (tauri/wry/specta/tauri-typed-ipc), then times a HOT rebuild -- only
# the fixture crate recompiles -- at each N, so the curve isolates the
# macro expansion + codegen, not the constant dependency tree. One cold
# build (cargo clean) at the largest N is the from-clean reference.
# Wall-clock, single-shot, machine-local -- directional, not CI grade.
# Run from benchmarks/.
set -eu
cd "$(dirname "$0")"

DIR=scaling-tmp
SIZES="1 8 64 256"

mkdir -p "$DIR/src"
cat > "$DIR/Cargo.toml" <<'EOF'
# Generated by ../scaling.sh -- gitignored, regenerated each run.
[package]
name = "ttipc-scaling"
version = "0.0.0"
edition = "2024"
publish = false

# Detach from the parent workspace.
[workspace]

[dependencies]
ttipc = { package = "tauri-typed-ipc", path = "../../tauri-typed-ipc" }
EOF

# gen N -- a trait of N procedures, its impl, and a build() that forces
# into_procedures so the generated dispatch + descriptor both compile.
gen() {
    n=$1
    echo "use ttipc::procedures;"
    echo "#[procedures]"
    echo "pub trait Wide {"
    i=0
    while [ "$i" -lt "$n" ]; do
        echo "    fn m$i(&self, n: u32) -> u32;"
        i=$((i + 1))
    done
    echo "}"
    echo "pub struct W;"
    echo "impl Wide for W {"
    i=0
    while [ "$i" -lt "$n" ]; do
        echo "    fn m$i(&self, n: u32) -> u32 { n }"
        i=$((i + 1))
    done
    echo "}"
    echo "pub fn build() -> ttipc::Procedures { W.into_procedures() }"
}

# Warm the dependency tree once so the per-N rebuilds below are pure
# fixture-crate compiles.
gen 1 > "$DIR/src/lib.rs"
(cd "$DIR" && cargo build --release -q)

for n in $SIZES; do
    gen "$n" > "$DIR/src/lib.rs"
    echo "== N=$n: hot (rewrite trait + rebuild, fixture crate only)"
    (cd "$DIR" && /usr/bin/time -p cargo build --release -q)
done

echo "== N=256: cold (cargo clean + build, from-clean reference)"
gen 256 > "$DIR/src/lib.rs"
(cd "$DIR" && cargo clean -q && /usr/bin/time -p cargo build --release -q)
